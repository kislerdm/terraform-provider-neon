func newBackupScheduleID(projectID, branchID string) string {
	return fmt.Sprintf("%s/%s", projectID, branchID)
}

func newBackupSchedule(items []backupScheduleItemModel) neon.BackupSchedule {
	result := neon.BackupSchedule{Schedule: make([]neon.BackupScheduleItem, 0, len(items))}
	for _, item := range items {
		entry := neon.BackupScheduleItem{Frequency: item.Frequency.ValueString()}
		if !item.Day.IsNull() && !item.Day.IsUnknown() {
			day := uint8(item.Day.ValueInt64())
			entry.Day = &day
		}
		if !item.Hour.IsNull() && !item.Hour.IsUnknown() {
			hour := uint8(item.Hour.ValueInt64())
			entry.Hour = &hour
		}
		if !item.Month.IsNull() && !item.Month.IsUnknown() {
			month := uint8(item.Month.ValueInt64())
			entry.Month = &month
		}
		if !item.RetentionSeconds.IsNull() && !item.RetentionSeconds.IsUnknown() {
			retention := uint32(item.RetentionSeconds.ValueInt64())
			entry.RetentionSeconds = &retention
		}
		result.Schedule = append(result.Schedule, entry)
	}
	return result
}

func newBackupScheduleItemsModel(items []neon.BackupScheduleItem) []backupScheduleItemModel {
	result := make([]backupScheduleItemModel, 0, len(items))
	for _, item := range items {
		model := backupScheduleItemModel{Frequency: types.StringValue(item.Frequency)}
		if item.Day != nil {
			model.Day = types.Int64Value(int64(*item.Day))
		}
		if item.Hour != nil {
			model.Hour = types.Int64Value(int64(*item.Hour))
		}
		if item.Month != nil {
			model.Month = types.Int64Value(int64(*item.Month))
		}
		if item.RetentionSeconds != nil {
			model.RetentionSeconds = types.Int64Value(int64(*item.RetentionSeconds))
		}
		result = append(result, model)
	}
	return result
}
